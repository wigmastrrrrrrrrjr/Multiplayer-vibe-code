// Wrangler-free deploy: bundle with esbuild (WASM build — works on any platform,
// including ones where workerd has no binaries) and deploy through the
// Cloudflare Workers JSON API (workers → version → deployment).
// Reads credentials from env: CLOUDFLARE_API_TOKEN / CLOUDFLARE_ACCOUNT_ID
// (e.g. gitignored .dev.vars). Also reads MCP_SIGNING_SECRET from env or
// .dev.vars and ships it as a secret_text binding.
//
// Usage: node deploy-worker.mjs <staging|prod>
import { readFile, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, initialize } from 'esbuild-wasm';

const here = dirname(fileURLToPath(import.meta.url));
const serverDir = resolve(here, '..');
const rootDir = resolve(serverDir, '..', '..');

/** Load KEY=VALUE lines from .dev.vars (simple parser; no quoting subtleties). */
async function loadDevVars() {
  try {
    const text = await readFile(resolve(rootDir, '.dev.vars'), 'utf8');
    const out = {};
    for (const line of text.split('\n')) {
      const m = line.match(/^\s*([A-Z0-9_]+)=(.*)\s*$/);
      if (m) out[m[1]] = m[2];
    }
    return out;
  } catch {
    return {};
  }
}

const envName = process.argv[2] ?? 'staging';
const SCRIPT_NAMES = { staging: 'mvc-server-staging', prod: 'mvc-server' };
const scriptName = SCRIPT_NAMES[envName];
if (!scriptName) throw new Error(`unknown env "${envName}" (use staging|prod)`);

const vars = await loadDevVars();
const API_TOKEN = process.env.CLOUDFLARE_API_TOKEN ?? vars.CLOUDFLARE_API_TOKEN;
const ACCOUNT_ID = process.env.CLOUDFLARE_ACCOUNT_ID ?? vars.CLOUDFLARE_ACCOUNT_ID;
const SIGNING_SECRET = process.env.MCP_SIGNING_SECRET ?? vars.MCP_SIGNING_SECRET;
if (!API_TOKEN || !ACCOUNT_ID) {
  console.error('set CLOUDFLARE_API_TOKEN and CLOUDFLARE_ACCOUNT_ID (gitignored .dev.vars)');
  process.exit(1);
}
if (!SIGNING_SECRET) {
  console.error(
    'set MCP_SIGNING_SECRET in .dev.vars — the Worker refuses to sign member tokens without it',
  );
  process.exit(1);
}

const COMPAT_DATE = '2025-06-01';
const MAIN_MODULE = 'index.mjs';
const D1_IDS = {
  staging: '6fc84178-ee37-4057-b93c-f226a9ba27ca',
  prod: '16cf0688-5357-4761-a149-bea7ab7e6c24',
};
const BINDINGS = [
  { type: 'durable_object_namespace', name: 'LOBBY_OBJECT', class_name: 'Lobby' },
  { type: 'd1', name: 'DB', id: D1_IDS[envName] },
  { type: 'secret_text', name: 'MCP_SIGNING_SECRET', text: SIGNING_SECRET },
];
const DO_MIGRATIONS = { new_sqlite_classes: ['Lobby'] };

/* 1b. Self-host the source: pack git-tracked files into a tarball, embed it in
 * a generated module that /source.tar.gz serves. `git archive` only contains
 * committed files, so untracked secrets (.dev.vars) can never ship. */
const SOURCE_TARBALL_MODULE = resolve(
  serverDir,
  'src/generated/source-tarball.ts',
);
async function writeSourceTarballModule() {
  let tgz;
  try {
    tgz = execFileSync(
      'git',
      ['archive', '--format=tar.gz', '--prefix=multiplayer-vibe-code/', 'HEAD'],
      { cwd: rootDir, maxBuffer: 10 * 1024 * 1024 },
    );
  } catch {
    // No git checkout (this dev box): pack the working tree, excluding secrets
    // and generated/installed state. The tarball is still self-hosted source.
    const name = basename(rootDir);
    const parent = dirname(rootDir);
    const excludes = [
      'node_modules',
      '.git',
      '.dev.vars',
      '.wrangler',
      'dist',
      'coverage',
      '.DS_Store',
      '*.log',
      '.tmp',
    ].flatMap((p) => [`--exclude=${p}`, `--exclude=*/${p}`]);
    tgz = execFileSync(
      'tar',
      ['-czf', '-', ...excludes, '-C', parent, name],
      { maxBuffer: 10 * 1024 * 1024 },
    );
    console.warn('git checkout not found — packed the working tree instead');
  }
  const sha256 = createHash('sha256').update(tgz).digest('hex');
  const builtAt = new Date().toISOString();
  await writeFile(
    SOURCE_TARBALL_MODULE,
    `// GENERATED by deploy-worker.mjs — do not edit; restored to placeholder after deploy.\n` +
      `export const SOURCE_TARBALL_B64 = '${tgz.toString('base64')}';\n` +
      `export const SOURCE_SHA256 = '${sha256}';\n` +
      `export const SOURCE_BUILT_AT = '${builtAt}';\n`,
  );
  console.log(`source tarball embedded (${(tgz.length / 1024).toFixed(1)} kB, sha256 ${sha256.slice(0, 12)}…)`);
}

/* 1. Bundle the Worker with esbuild (WASM) -------------------------------- */
const sourcePlaceholder = await readFile(SOURCE_TARBALL_MODULE, 'utf8').catch(() => '');
await initialize({}); // Node loads esbuild.wasm from disk automatically
await writeSourceTarballModule();
await build({
  absWorkingDir: serverDir,
  entryPoints: ['src/index.ts'],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  outfile: 'dist/worker.mjs',
  minify: true,
  logLevel: 'info',
});
const code = await readFile(resolve(serverDir, 'dist/worker.mjs'), 'utf8');

// Restore the committed placeholder so the working tree is clean for the next
// deploy (the bundle above already inlined the tarball).
try {
  execFileSync('git', ['checkout', '--', 'src/generated/source-tarball.ts'], {
    cwd: serverDir,
    stdio: 'ignore',
  });
} catch {
  await writeFile(SOURCE_TARBALL_MODULE, sourcePlaceholder);
}

/* 2. Cloudflare API helpers -------------------------------------------------- */
const api = (path) =>
  `https://api.cloudflare.com/client/v4/accounts/${ACCOUNT_ID}${path}`;

async function call(path, opts = {}) {
  const res = await fetch(api(path), {
    ...opts,
    headers: {
      Authorization: `Bearer ${API_TOKEN}`,
      ...(opts.body ? { 'content-type': 'application/json' } : {}),
      ...opts.headers,
    },
  });
  const body = await res.json().catch(() => ({}));
  if (!res.ok || body.success === false) {
    const err = new Error(
      `${opts.method ?? 'GET'} ${path} -> ${res.status}: ${JSON.stringify(body.errors ?? body)}`,
    );
    err.status = res.status;
    err.body = body;
    throw err;
  }
  return body.result;
}

async function createVersion(workerId, { bindings = false, migrations = false } = {}) {
  const version = {
    compatibility_date: COMPAT_DATE,
    main_module: MAIN_MODULE,
    modules: [
      {
        name: MAIN_MODULE,
        content_type: 'application/javascript+module',
        content_base64: Buffer.from(code).toString('base64'),
      },
    ],
  };
  if (bindings) version.bindings = BINDINGS;
  if (migrations) version.migrations = DO_MIGRATIONS;
  return call(`/workers/workers/${workerId}/versions`, {
    method: 'POST',
    body: JSON.stringify(version),
  });
}

async function deploy(workerId, versionId) {
  return call(`/workers/scripts/${scriptName}/deployments`, {
    method: 'POST',
    body: JSON.stringify({
      strategy: 'percentage',
      versions: [{ percentage: 100, version_id: versionId }],
    }),
  });
}

/* 3. Ensure the Worker exists ------------------------------------------------ */
let workerId;
let haveDeployment = false;
try {
  const worker = await call(`/workers/workers/${scriptName}`);
  workerId = worker.id;
  console.log(`worker "${scriptName}" exists (${workerId})`);
} catch (err) {
  if (err.status !== 404) throw err;
  console.log(`creating worker "${scriptName}"…`);
  const created = await call(`/workers/workers`, {
    method: 'POST',
    body: JSON.stringify({
      name: scriptName,
      subdomain: { enabled: true },
      observability: { enabled: true },
    }),
  });
  workerId = created.id;
}
try {
  const res = await call(`/workers/scripts/${scriptName}/deployments`);
  // The endpoint may return an array or { deployments: [...] } depending on API shape.
  const list = Array.isArray(res) ? res : res?.deployments;
  haveDeployment = Array.isArray(list) && list.length > 0;
} catch {
  haveDeployment = false;
}

/* 4. Upload version(s) + deploy --------------------------------------------- */
const deployWithBindings = async (workerId) => {
  const v = await createVersion(workerId, { bindings: true });
  await deploy(workerId, v.id);
  console.log(`deployed version ${v.id} (${(code.length / 1024).toFixed(1)} kB)`);
};

if (haveDeployment) {
  // Durable Object class already deployed: single version, bindings only.
  try {
    await deployWithBindings(workerId);
  } catch (err) {
    // Self-heal: class never migrated (e.g. interrupted first deploy). Run the
    // migration phase first, then the bindings phase.
    if (!String(err.message).toLowerCase().includes('migration')) throw err;
    console.log('DO class not migrated yet — running migration phase first…');
    const m = await createVersion(workerId, { migrations: true });
    await deploy(workerId, m.id);
    await deployWithBindings(workerId);
  }
} else {
  // First deploy, three phases (docs: a DO binding is rejected until the
  // migration that creates the class has been applied by a deployment):
  //   1. base module              → deploy
  //   2. + migration (DO + SQLite)→ deploy
  //   3. + binding                → deploy
  const v1 = await createVersion(workerId);
  await deploy(workerId, v1.id);
  console.log('phase 1/3: base version deployed');
  const v2 = await createVersion(workerId, { migrations: true });
  await deploy(workerId, v2.id);
  console.log('phase 2/3: migration (Durable Object + SQLite) applied');
  await deployWithBindings(workerId);
  console.log('phase 3/3: DO binding live');
}

const accountSub = (await call('/workers/subdomain')).subdomain;
console.log(`live: https://${scriptName}.${accountSub}.workers.dev`);